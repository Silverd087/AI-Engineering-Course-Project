"""Builds report.html and report.pdf (one page) from the real results files.

Usage:
    python src/report.py

Reads results/summary.csv, results/per_item.csv, results/cost_model.json,
results/hardware_note.md and results/choice.md (the team's written decision).
Every number in the report comes from those files -- nothing is typed by hand.
The PDF is printed with headless Chrome/Edge.
"""
import csv
import html
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import config  # noqa: E402
import run  # noqa: E402

E = html.escape
ROLE = {"top": "Top API", "cheap": "Cheap API", "local": "Open-weights, local"}


def _money(x):
    x = float(x)
    return f"${x:,.2f}" if x >= 1 else f"${x:.3f}"


def _rows(s, n=3):
    try:
        rows = json.loads(s) if s else None
    except json.JSONDecodeError:
        return s
    if rows is None:
        return "—"
    txt = "; ".join(", ".join(str(v) for v in r) for r in rows[:n])
    return txt + (" …" if len(rows) > n else "") if rows else "(0 rows)"


def pick_wrong(per_item, model, k=3):
    """Three wrong test answers, preferring different failure types."""
    wrong = [r for r in per_item if r["model"] == model and r["split"] == "test" and r["correct"] == "0"]
    chosen, seen = [], set()
    for r in wrong:
        if r["failure"] not in seen:
            chosen.append(r); seen.add(r["failure"])
    for r in wrong:
        if len(chosen) >= k:
            break
        if r not in chosen:
            chosen.append(r)
    return chosen[:k]


def find_browser():
    for p in [os.environ.get("CHROME", ""),
              r"C:\Program Files\Google\Chrome\Application\chrome.exe",
              r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
              shutil.which("google-chrome") or "", shutil.which("chromium") or "", shutil.which("chrome") or "",
              "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"]:
        if p and Path(p).exists():
            return p
    return None


def update_readme(summary):
    """Rewrites the results table in README.md between the RESULTS markers."""
    readme = config.ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    start, end = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
    if start not in text or end not in text:
        return
    lines = ["| Model | Accuracy (test, n/50) | Wrong / SQL err / parse / other | p50 (ms) | p95 (ms) | Cost / 1k req | $/month at 100x |",
             "|---|---|---|---|---|---|---|"]
    for s in summary:
        other = int(s["refusal"]) + int(s["timeout"]) + int(s["api_error"])
        lines.append(f"| {ROLE.get(s['model'], s['model'])}: `{s['model_name']}` | **{s['accuracy']}** | "
                     f"{s['wrong_result']} / {s['sql_error']} / {s['parse_error']} / {other} | "
                     f"{float(s['p50_ms']):,.0f} | {float(s['p95_ms']):,.0f} | {_money(s['cost_per_1k_usd'])} | "
                     f"{_money(s['monthly_usd_100x'])} |")
    lines.append(f"\n_Generated by `src/report.py` from `results/summary.csv`, runs dated {summary[0].get('run_date', '')}._")
    a, b = text.index(start) + len(start), text.index(end)
    readme.write_text(text[:a] + "\n" + "\n".join(lines) + "\n" + text[b:], encoding="utf-8")
    print("-> README.md results table")


def build():
    R = config.RESULTS
    summary = list(csv.DictReader(open(R / "summary.csv", encoding="utf-8")))
    per_item = list(csv.DictReader(open(R / "per_item.csv", encoding="utf-8")))
    cost = json.loads((R / "cost_model.json").read_text(encoding="utf-8"))
    items = {it["id"]: it for it in run.load_items(config.ITEMS_PATH)}
    hw = (R / "hardware_note.md").read_text(encoding="utf-8") if (R / "hardware_note.md").exists() else ""
    choice_path = R / "choice.md"
    choice = choice_path.read_text(encoding="utf-8").strip() if choice_path.exists() else \
        "<b>TODO:</b> write results/choice.md after reading the results."
    hw_lines = [l[2:] for l in hw.splitlines() if l.startswith("- ")][:6]
    n_test = sum(1 for it in items.values() if it.get("split") == "test")
    n_dev = len(items) - n_test
    ex = items["q044"]
    run_date = summary[0].get("run_date", "")
    a = cost["assumptions"]

    res_rows = "".join(
        f"<tr><td><b>{ROLE.get(s['model'], s['model'])}</b><br><code>{E(s['model_name'])}</code></td>"
        f"<td class=n><b>{s['accuracy']}</b> ({s['accuracy_pct']}%)</td>"
        f"<td class=n>{s['wrong_result']}/{s['sql_error']}/{s['parse_error']}/{int(s['refusal']) + int(s['timeout']) + int(s['api_error'])}</td>"
        f"<td class=n>{float(s['p50_ms']):,.0f}</td><td class=n>{float(s['p95_ms']):,.0f}</td>"
        f"<td class=n>{_money(s['cost_per_1k_usd'])}</td>"
        f"<td class=n>{_money(s['monthly_usd_today'])}</td><td class=n>{_money(s['monthly_usd_100x'])}</td></tr>"
        for s in summary)

    wrong_html = ""
    for s in summary:
        picks = pick_wrong(per_item, s["model"])
        if not picks:
            wrong_html += f"<p><b>{E(s['model_name'])}</b>: no wrong answers on the test split.</p>"
            continue
        wrong_html += f"<p class=wm><b>{E(s['model_name'])}</b></p><ul>" + "".join(
            f"<li><b>{r['id']}</b> <i>{E(items[r['id']]['question'][:80])}{'…' if len(items[r['id']]['question']) > 80 else ''}</i>"
            f"<br><code>{E((r['candidate_sql'] or '(no SQL parsed)')[:120])}</code>"
            f"<br><span class=why>"
            + (f"wrong result: expected {E(_rows(r['expected_rows']))} · got {E(_rows(r['actual_rows']))}" if r['failure'] == 'wrong_result'
               else E(r['error'][:100]))
            + "</span></li>" for r in picks) + "</ul>"

    be = "".join(
        f"<li>vs {E(cost['models'][m]['model_name'])}: <b>{b['requests_per_day']:,.0f} req/day</b>"
        f"{'' if b['within_one_box_capacity'] else f' — more than one GPU can serve ({b['one_box_capacity_per_month'] / 30:,.0f}/day), so never on this hardware'}</li>"
        for m, b in cost.get("break_even", {}).items())
    local = next((s for s in summary if s["model"] == "local"), None)

    doc = f"""<!doctype html><html><head><meta charset=utf-8><title>Project 0 Bake-Off report</title><style>
@page {{ size: A4; margin: 11mm 12mm; }}
body {{ font: 8.1pt/1.28 "Segoe UI", system-ui, sans-serif; color:#16191d; margin:0; }}
h1 {{ font-size:14pt; margin:0; }} .meta {{ color:#59616b; margin:1px 0 6px; }}
h2 {{ font-size:9.2pt; margin:7px 0 3px; color:#1d3f6e; border-bottom:1px solid #d6dbe2; padding-bottom:1px; }}
.cols {{ column-count:2; column-gap:6mm; }} h2 {{ break-after:avoid; }}
p {{ margin:2px 0 4px; }} ul {{ margin:2px 0 4px; padding-left:13px; }} li {{ margin-bottom:2px; }}
code {{ font: 7.4pt Consolas, monospace; background:#f1f3f6; padding:0 2px; }}
table {{ width:100%; border-collapse:collapse; font-size:8pt; }}
th, td {{ border-bottom:1px solid #e1e4e9; padding:2.5px 4px; text-align:left; vertical-align:top; }}
th {{ background:#eef2f7; font-size:7.4pt; }} .n {{ text-align:right; white-space:nowrap; }}
.why {{ color:#a32d2d; }} .wm {{ margin:3px 0 0; }} .choice {{ background:#eef4fb; border-left:3px solid #1d3f6e; padding:4px 7px; margin:3px 0; }}
.small {{ color:#59616b; font-size:7.4pt; }}
</style></head><body>
<h1>Project 0 — Bake-Off: writing SQL from a question</h1>
<div class=meta>CS496 AI Engineering · Fall 2026 · runs dated {E(run_date)} · repo: README.md, data/, src/, results/</div>

<h2>Results (test split, n = {n_test})</h2>
<table><tr><th>Model</th><th class=n>Accuracy</th><th class=n>fails: wrong / sql / parse / other</th>
<th class=n>p50 ms</th><th class=n>p95 ms</th><th class=n>$ / 1k req</th><th class=n>$ / month today</th><th class=n>$ / month 100×</th></tr>{res_rows}</table>
<p class=small>Latency: wall time from sending the request to the full answer, {summary[0]['calls_timed']} sequential calls per model (dev+test), nearest-rank percentiles.
Today = {a['today_requests_per_day']:,} requests/day, 100× = {a['today_requests_per_day'] * 100:,}/day.
{f"Local model generated {local['tokens_per_s']} tokens/s." if local and local.get('tokens_per_s') else ''} Built from results/per_item.csv by src/cost.py.</p>

<div class=cols>
<section><h2>1 · Task and an example item</h2>
<p>Given a question in English and the schema of a 5-table bookstore database (authors, books, customers, orders, order_items),
the model writes one SQLite query. We run the model's query and the reference query on the same database and compare the
<b>result sets</b> (order-independent, floats to 1e-6), so different but equivalent SQL is still marked right. No LLM grades anything.</p>
<p><b>{ex['id']}</b>: <i>{E(ex['question'])}</i><br>Reference: <code>{E(ex['reference_sql'])}</code></p></section>

<section><h2>2 · Data</h2>
<p>{len(items)} hand-written items over a hand-written seed DB (20 books, 10 customers, 15 orders, 30 order lines), covering
filters, aggregates, GROUP BY/HAVING, 2–5 table joins, subqueries, anti-joins, CASE and date functions. Every reference query
was run to make sure it returns a non-empty answer, and ORDER BY … LIMIT items were checked for ties at the cut-off.
Two team members each write their own SQL without looking at the reference and compare results; a disagreement means the
question is ambiguous and it is rewritten (data/labelling_note.md). <b>Split:</b> {n_dev} dev items (used while writing the prompt), {n_test} frozen test items (the numbers reported).</p></section>

<section><h2>3 · Setup</h2>
<ul><li>Top: <code>{E(config.MODELS['top']['name'])}</code> · Cheap: <code>{E(config.MODELS['cheap']['name'])}</code> (OpenAI API) ·
Local: <code>{E(config.MODELS['local']['name'])}</code> via Ollama</li>
<li>One prompt for all (src/prompt.txt: schema + question + “reply with one ```sql block”), one parser (src/run.py <code>extract_sql</code>),
max {config.MAX_OUTPUT_TOKENS} output tokens, {config.REQUEST_TIMEOUT_S}s timeout, same {len(items)} items in the same order.</li>
<li>Temperature {config.TEMPERATURE} on the local model. <b>Deviation:</b> OpenAI reasoning models reject a <code>temperature</code> setting, so they
run at their fixed default; both use reasoning effort “{config.REASONING_EFFORT}” (reasoning tokens are billed as output and counted in cost).</li>
<li>Hardware: {E('; '.join(hw_lines)) or 'see results/hardware_note.md'}</li></ul></section>

<section><h2>4 · Three wrong answers per model</h2>{wrong_html}</section>

<section><h2>5 · Our choice</h2><div class=choice>{choice}</div></section>

<section><h2>6 · Cost at 100× traffic and break-even</h2>
<p>API cost = mean tokens from the <code>usage</code> field × list price, so it scales linearly. Self-hosted = laptop GPU
(${a['hardware_price_usd']:,.0f} over {a['hardware_life_hours']:,} h, {a['power_kw']} kW at ${a['electricity_usd_per_kwh']}/kWh) ÷ measured requests/hour,
plus {a['ops_hours_per_month']} h/month of our time at ${a['engineer_usd_per_hour']}/h. At 100× it needs as many always-on boxes as throughput requires.
Break-even = daily volume where one dedicated box + ops time costs the same as the API:</p><ul>{be}</ul></section>
</div></body></html>"""
    update_readme(summary)
    out_html = config.ROOT / "report.html"
    out_html.write_text(doc, encoding="utf-8")
    print(f"-> {out_html}")

    browser = find_browser()
    if not browser:
        print("No Chrome/Edge found: open report.html and print it to report.pdf.")
        return
    out_pdf = config.ROOT / "report.pdf"
    subprocess.run([browser, "--headless=new", "--disable-gpu", "--no-pdf-header-footer",
                    f"--print-to-pdf={out_pdf}", out_html.as_uri()], check=True,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=120)
    print(f"-> {out_pdf}")


if __name__ == "__main__":
    build()
